import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const run = spawnSync("cargo", ["run", "--locked", "--quiet", "-p", "mon-contracts", "--bin", "export-schema"], { cwd: resolve(app, ".."), encoding: "utf8", maxBuffer: 16 * 1024 * 1024 });
if (run.status !== 0) throw Error(run.stderr || String(run.error ?? "Contract exporter failed"));
const bundle = JSON.parse(run.stdout);
if (bundle.schemaVersion !== 1 || !bundle.contracts) throw Error("Unsupported contract export");
function browserSchema(value) {
  if (Array.isArray(value)) return value.map(browserSchema);
  if (!value || typeof value !== "object") return value;
  const result = Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, browserSchema(nested)]));
  const ranges = { uint32: [0, 4_294_967_295], int32: [-2_147_483_648, 2_147_483_647], uint64: [0, Number.MAX_SAFE_INTEGER], int64: [Number.MIN_SAFE_INTEGER, Number.MAX_SAFE_INTEGER] };
  if (ranges[result.format]) {
    const [min, max] = ranges[result.format];
    delete result.format;
    result.minimum = Math.max(result.minimum ?? min, min);
    result.maximum = Math.min(result.maximum ?? max, max);
  }
  return result;
}
const banner = "// Generated by npm run generate:contracts. Do not edit.\n";
let guards = banner + 'import type * as Contract from "./contracts";\n';
const ajv = new Ajv({ strict: true, code: { source: true, esm: true, lines: true }, allErrors: false });
addFormats(ajv);
const exports = {}, definitions = {}, names = [];
function definition(name, value) {
  const { $schema: _schema, $id: _id, title: _title, definitions: _definitions, ...shape } = value;
  if (definitions[name] && JSON.stringify(definitions[name]) !== JSON.stringify(shape)) throw Error(`Conflicting Rust schema definition: ${name}`);
  definitions[name] = shape;
}
for (const [name, schema] of Object.entries(bundle.contracts).sort(([a], [b]) => a.localeCompare(b))) {
  const wireSchema = browserSchema(schema);
  for (const [dependency, nested] of Object.entries(wireSchema.definitions ?? {})) definition(dependency, nested);
  definition(name, wireSchema); names.push(name);
  ajv.addSchema({ ...wireSchema, $id: name }, name);
  exports[`validate${name}`] = name;
  guards += `export function validate${name}(value: unknown): value is Contract.${name};\n`;
}
// Compile one graph: shared Rust definitions appear once even when exported both
// as standalone DTOs and nested fields of another contract.
const declarations = banner + await compile({
  $schema: "http://json-schema.org/draft-07/schema#",
  anyOf: names.map(name => ({ $ref: `#/definitions/${name}` })),
  definitions,
}, "NativeContract", { bannerComment: "", unreachableDefinitions: false });
const files = { "contracts.ts": declarations, "validators.js": banner + standaloneCode(ajv, exports), "validators.d.ts": guards, "contracts.schema.json": JSON.stringify(bundle, null, 2) + "\n" };
const output = resolve(app, "src/generated");
const check = process.argv.includes("--check");
if (!check) mkdirSync(output, { recursive: true });
for (const [name, text] of Object.entries(files)) {
  const path = resolve(output, name);
  if (check) {
    if (readFileSync(path, "utf8").replaceAll("\r\n", "\n") !== text) throw Error(`Generated contract differs: ${name}. Run npm run generate:contracts.`);
  } else writeFileSync(path, text);
}
console.log(`${check ? "Verified" : "Generated"} ${Object.keys(bundle.contracts).length} Rust contracts`);
