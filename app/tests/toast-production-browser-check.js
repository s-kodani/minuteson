// Current individual editing UI; no removed bulk-edit/adoption/undo surface.
async page => {
  const results = [], check = (value, message) => { if (!value) throw Error(message); };
  const host = page.getByRole("complementary", { name: "通知", exact: true });
  await page.getByRole("button", { name: "会議A", exact: true }).click();
  const editor = page.getByRole("region", { name: "文字起こし編集", exact: true });
  const body = editor.getByRole("button", { name: "00:00:00の発言を編集", exact: true });
  const text = editor.getByRole("textbox", { name: "00:00:00の発言", exact: true });
  const commit = () => editor.locator(".utterance-text-edit").getByRole("button", { name: "保存", exact: true }).click();
  await body.click(); await text.fill("点検日について修正した本文です。"); await commit();
  await text.waitFor({ state: "hidden" });
  check(await host.locator(".toast-card").count() === 0, "ordinary saving generated success notifications");
  results.push("ordinary individual saving emits no routine toast");
  await page.evaluate(() => { window.monBrowserFixture.failSave = true; });
  await body.click(); await text.fill("保存できない点検日を保持します。"); await commit();
  const alert = host.getByRole("alert").filter({ hasText: "文字起こしの保存" });
  await alert.waitFor();
  check(await alert.count() === 1, "save failure produced duplicate toasts");
  const writes = await page.evaluate(() => window.monBrowserFixture.calls.filter(c => c.command === "save_transcript_draft").length);
  await host.getByRole("button", { name: "エラー通知を閉じる", exact: true }).click();
  check(await text.inputValue() === "保存できない点検日を保持します。" && await editor.getByRole("button", { name: "保存を再試行", exact: true }).isEnabled(), "dismissal discarded input or disabled retry");
  check(await page.evaluate(() => window.monBrowserFixture.calls.filter(c => c.command === "save_transcript_draft").length) === writes, "dismissal retried saving");
  results.push("one important error toast; dismissal preserves input without writes");
  await page.evaluate(() => { window.monBrowserFixture.failSave = false; });
  await editor.getByRole("button", { name: "保存を再試行", exact: true }).click();
  await text.waitFor({ state: "hidden" });
  check(await body.innerText() === "保存できない点検日を保持します。", "retry rewrote human text");
  await alert.waitFor({ state: "hidden" });
  check(await host.getByRole("alert").count() === 0, "saved issue stayed active");
  results.push("explicit retry persists the exact text and resolves the originating issue");
  await page.evaluate(() => { window.monBrowserFixture.failSave = true; });
  await body.click(); await text.fill("通知から保存を再試行する本文です。"); await commit();
  await host.getByRole("button", { name: "文字起こし保存を再試行", exact: true }).waitFor();
  const before = await page.evaluate(() => window.monBrowserFixture.calls.filter(c => c.command === "save_transcript_draft").length);
  await page.evaluate(() => { window.monBrowserFixture.failSave = false; });
  await host.getByRole("button", { name: "文字起こし保存を再試行", exact: true }).click();
  await text.waitFor({ state: "hidden" }); await alert.waitFor({ state: "hidden" });
  check(await body.innerText() === "通知から保存を再試行する本文です。", "toast retry lost input");
  check(await page.evaluate(() => window.monBrowserFixture.calls.filter(c => c.command === "save_transcript_draft").length) === before + 1, "toast retry duplicated writes");
  results.push("toast retry makes one explicit queue write and resolves after persistence");
  return { passed: results.length, results };
}
