async(page,capturePath,detailUI)=>{
  const results=[],check=(ok,message)=>{if(!ok)throw Error(message);};
  const prefix=String.fromCharCode(92).repeat(2)+"?";
  const unchanged=()=>page.evaluate(()=>{
    const f=window.pathDiagnosticsFixture;
    return [f.preview.meetingRoot,f.preview.archivePath,f.progress.detail,f.entry.message,f.entry.source,f.report.failure.message].every(value=>value.includes(String.fromCharCode(92).repeat(2)+"?"));
  });
  const withoutPrefix=async locator=>check(!(await locator.innerText()).includes(prefix),"extended prefix remains in rendered diagnostic");
  await page.getByRole("region",{name:"初期化表示",exact:true}).waitFor();
  await withoutPrefix(page.getByRole("region",{name:"初期化表示",exact:true}));
  await withoutPrefix(page.getByRole("region",{name:"進捗表示",exact:true}));
  check(await unchanged(),"render changed reset/progress/log/startup DTO");
  results.push("reset paths, status/error and progress diagnostics format only on render");
  await page.getByRole("button",{name:"確認を開く",exact:true}).click();
  const confirmation=page.getByRole("dialog",{name:"保存先を確認",exact:true});
  await confirmation.waitFor(); await withoutPrefix(confirmation);
  check(await page.evaluate(()=>window.pathDiagnosticsFixture.confirmation().target===window.pathDiagnosticsFixture.path),"confirmation target mutated");
  await confirmation.getByRole("button",{name:"実行する",exact:true}).click();
  await confirmation.getByRole("alert").waitFor(); await withoutPrefix(confirmation);
  check(await page.evaluate(()=>window.pathDiagnosticsFixture.commands[0]===window.pathDiagnosticsFixture.path),"action received display path instead of native target");
  await confirmation.getByRole("button",{name:"確認を閉じる",exact:true}).click();
  results.push("confirmation target, explanation and inline failure are formatted; action keeps original target");
  await page.getByRole("button",{name:"通知を表示",exact:true}).click();
  const notifications=page.getByRole("complementary",{name:"通知",exact:true});
  await notifications.getByRole("alert").waitFor(); await withoutPrefix(notifications);
  await page.getByRole("region",{name:"通知一覧の内容",exact:true}).getByText(/保存内容を確認できません/).waitFor();
  await withoutPrefix(page.getByRole("region",{name:"通知一覧の内容",exact:true}));
  check(await page.evaluate(()=>{const f=window.pathDiagnosticsFixture,n=f.notice().find(n=>n.key==="original-notice");return n.message===f.diagnostic&&n.details===f.unc;}),"notification raw contents or identity changed");
  await notifications.getByRole("button",{name:"エラー通知の詳細の説明を開く",exact:true}).click();
  await withoutPrefix(page.getByRole("dialog",{name:"エラー通知の詳細",exact:true}));
  results.push("notification body, details and history hide prefixes while retaining raw state");
  await page.goto("http://127.0.0.1:1420/?display=startup");
  await page.getByRole("main",{name:"起動診断",exact:true}).waitFor();
  await page.getByLabel("保持した起動診断",{exact:true}).waitFor();
  await page.getByRole("region",{name:"データの初期化",exact:true}).getByRole("alert").waitFor();
  await withoutPrefix(page.getByRole("main",{name:"起動診断",exact:true}));
  check(await unchanged(),"startup rendering changed retained diagnostics");
  results.push("startup selected roots and retained failure text format without mutating report");
  await detailUI.prepareClipboard();
  await page.goto("http://127.0.0.1:1420/?display=logs");
  await page.getByRole("tab",{name:"エンジンログ",exact:true}).click();
  const row=page.locator(".internal-logs tbody tr"); await row.waitFor();
  await withoutPrefix(page.locator(".internal-logs"));
  check((await row.locator(".internal-log-message pre").innerText()).length===240,"log list was shortened before conversion");
  await row.getByRole("button",{name:/のログ詳細/}).focus();
  const details=page.getByRole("dialog",{name:"ログ詳細",exact:true}); await details.waitFor(); await withoutPrefix(details);
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:"表示中ログをコピー",exact:true}).click();
  const copied=await page.evaluate(()=>navigator.clipboard.readText());
  check(!copied.includes(prefix)&&copied.includes("operation=operation-original")&&copied.includes("meeting=meeting-original"),"copy changed identifiers or retained path prefix");
  check(await unchanged(),"log display/copy changed original entries");
  await page.screenshot({path:capturePath("native-path-diagnostics.png")});
  results.push("log list, detail, execution source and clipboard format paths and preserve source logs and IDs");
  return {passed:results.length,results};
}
