// Actual production components, synthetic storage and silent PCM only.
async (page, capturePath = name => `output/playwright/${name}`) => {
  const check=(ok,message)=>{if(!ok)throw Error(message);}, results=[];
  await page.setViewportSize({width:1280,height:820});
  await page.goto('http://127.0.0.1:1420/tests/plain-minutes-interval-browser.html');
  await page.getByRole('button',{name:'議事録UI確認',exact:true}).first().waitFor();
  await page.evaluate(()=>{
    window.__mon.audioSummary.modes=['mixed'];
    window.__mon.plain.m1.markdown='# 議事録\n\n## 要約\nデータ管理の検討範囲と優先順位を確認した。\n\n## 決定事項\n- データ品質とセキュリティを重点対象にする。[00:00:01–00:00:04](audio:00:00:01-00:00:04)\n- 各システムのアクションを優先順位付けする。[00:00:04–00:00:04.250000](audio:00:00:04-00:00:04.250000)\n- ディメンションを分析の軸として整理する。[00:00:06–00:00:08](audio:00:00:06-00:00:08)\n';
  });
  await page.getByRole('button',{name:'議事録UI確認',exact:true}).first().click();
  await page.getByRole('tab',{name:'議事録',exact:true}).click();
  const links=page.locator('.markdown-audio-link');await links.nth(2).waitFor();
  const player=()=>page.getByRole('group',{name:'会議全体の音声再生',exact:true});
  const calls=cmd=>page.evaluate(cmd=>window.__mon.intervalCalls.filter(c=>c.cmd===cmd),cmd);
  const ready=async()=>{
    await page.waitForFunction(()=>{const c=window.__mon.intervalCalls, n=c.filter(c=>c.cmd==='prepare_meeting_playback').length;return c.some(c=>c.cmd==='read_playback_chunk'&&c.args.token===`interval-${n}`);});
    await player().getByRole('button',{name:'一時停止',exact:true}).waitFor();
  };
  const latest=()=>page.evaluate(()=>window.__mon.intervalCalls.filter(c=>c.cmd==='prepare_meeting_playback').at(-1)?.args.request.startReference?.startUs);
  for (const theme of ['light','dark']) {
    await page.evaluate(theme=>{document.documentElement.dataset.theme=theme;},theme);
    check(await links.evaluateAll(nodes=>nodes.every(node=>{const r=node.getBoundingClientRect(),s=getComputedStyle(node);return r.height<=24&&r.height>=20&&parseFloat(s.borderRadius)>=10&&parseFloat(s.fontSize)<=12;})),`tags too tall in ${theme}`);
    await page.screenshot({path:capturePath(`minutes-audio-tags-${theme}.png`)});
  }
  results.push('compact pill tags are 22px high in light and dark themes');
  await links.nth(0).click();await ready();
  await links.nth(1).evaluate(el=>{window.savedAudioTag=el;});
  const box=await links.nth(1).boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);
  await page.mouse.down();await page.waitForTimeout(350);
  check(await page.evaluate(()=>window.savedAudioTag.isConnected&&window.savedAudioTag===document.querySelectorAll('.markdown-audio-link')[1]),'playback clock replaced the clicked tag');
  await page.mouse.up();await ready();check(await latest()===4000000,'held click during playback did not select the next interval');
  results.push('button identity and pointer click survive multiple playback clock renders; playing A switches to B');
  const slider=()=>player().getByRole('slider',{name:'会議全体の再生位置',exact:true});
  check(await slider().getAttribute('max')==='960000','slider is clipped to the reference');
  await page.waitForFunction(()=>Number(document.querySelector('.audio-controls input[type=range]').value)>68000);
  check(await player().getByRole('button',{name:'一時停止',exact:true}).isVisible(),'playback stopped at the reference end');
  results.push('full timeline continues beyond the clicked 4–4.25 second reference');
  await slider().fill('958400');
  await player().getByRole('button',{name:'再生',exact:true}).waitFor();
  await links.nth(2).evaluate(el=>{window.completedAudioTag=el;});
  const idleBox=await links.nth(2).boundingBox();await page.mouse.move(idleBox.x+idleBox.width/2,idleBox.y+idleBox.height/2);
  await page.mouse.down();await page.waitForTimeout(3200);
  check(await page.evaluate(()=>window.completedAudioTag.isConnected&&window.completedAudioTag===document.querySelectorAll('.markdown-audio-link')[2]),'idle metadata refresh replaced the tag');
  await page.mouse.up();await ready();check(await latest()===6000000,'click after natural completion failed');
  const before=(await calls('prepare_meeting_playback')).length;
  await links.nth(2).click();await ready();
  check((await calls('prepare_meeting_playback')).length===before+1,'same interval could not restart');
  results.push('natural completion permits another interval and the same interval can restart');
  const pendingBefore=(await calls('prepare_meeting_playback')).length;
  await page.evaluate(()=>window.__mon.intervalMode='held');await links.nth(0).click();
  await page.waitForFunction(before=>window.__mon.intervalCalls.filter(c=>c.cmd==='prepare_meeting_playback').length===before+1,pendingBefore);
  await player().getByRole('button',{name:'再生準備を取り消す',exact:true}).waitFor();
  await page.evaluate(()=>{window.oldIntervalRelease=window.__mon.intervalRelease;window.__mon.intervalMode='success';});
  await links.nth(2).click();await ready();
  const token=await page.evaluate(()=>window.__mon.intervalCalls.filter(c=>c.cmd==='read_playback_chunk').at(-1).args.token);
  await page.evaluate(()=>window.oldIntervalRelease());
  await page.waitForFunction(()=>window.__mon.intervalCalls.some(c=>c.cmd==='cancel_playback_preparation'));
  check(await latest()===6000000,'late preparation selected an obsolete interval');
  check(await page.evaluate(token=>!window.__mon.intervalCalls.some(c=>c.cmd==='close_playback'&&c.args.token===token),token),'late preparation closed the current interval');
  results.push('switching during native preparation cancels the old request and its late response cannot replace or close current audio');
  await player().getByRole('button',{name:'一時停止',exact:true}).click();
  await player().getByRole('combobox',{name:'速度',exact:true}).selectOption('1.5');
  const beforeMode=await slider().inputValue();
  check(await page.getByRole('button',{name:'再生設定',exact:true}).count()===0,'removed playback settings remain');
  check(await slider().inputValue()===beforeMode,'checking playback controls reset reference position');
  await page.getByRole('tab',{name:'文字起こし',exact:true}).click();
  const row=page.locator('[data-utterance-id="u"]');
  await row.getByRole('button',{name:'音声を再生',exact:true}).click();await ready();
  check(await latest()===1000000,'utterance did not start at its absolute time');
  check(await page.evaluate(()=>window.__mon.intervalCalls.filter(c=>c.cmd==='prepare_meeting_playback').at(-1).args.request.mode)==='mixed','utterance did not use canonical meeting audio');
  check(await player().getByRole('combobox',{name:'速度',exact:true}).inputValue()==='1.5','entry point reset the shared speed');
  await page.waitForFunction(()=>Number(document.querySelector('.audio-controls input[type=range]').value)>48000);
  check(await player().getByRole('button',{name:'一時停止',exact:true}).isVisible(),'utterance stopped at its end');
  await player().getByRole('button',{name:'一時停止',exact:true}).click();
  const rowStarts=(await calls('prepare_meeting_playback')).length;
  await slider().fill('960000');await row.focus();await row.press('Space');await ready();
  check((await calls('prepare_meeting_playback')).length===rowStarts+1&&await latest()===1000000,'row Space after EOF did not prepare its reference');
  check(await page.evaluate(()=>{const c=window.__mon.intervalCalls,n=c.filter(c=>c.cmd==='prepare_meeting_playback').length;return c.find(c=>c.cmd==='read_playback_chunk'&&c.args.token===`interval-${n}`).args.offsetFrames;})===16000,'row Space after EOF restarted at the meeting beginning');
  await player().getByRole('button',{name:'一時停止',exact:true}).click();
  await slider().fill('0');check(await slider().inputValue()==='0','cannot seek before the clicked reference');
  results.push('utterances use the same canonical full player and speed and continue after their end');
  await page.getByRole('tab',{name:'議事録',exact:true}).click();await links.nth(2).click();await ready();
  check(await page.evaluate(()=>window.__mon.intervalCalls.filter(c=>c.cmd==='prepare_meeting_playback').at(-1).args.request.mode)==='mixed','minutes did not use canonical meeting audio');
  results.push('minutes and utterances share canonical meeting audio');
  await page.locator('.sidebar').getByRole('button',{name:'会議一覧',exact:true}).click();
  await page.getByRole('heading',{name:'会議一覧',exact:true}).waitFor();
  await player().waitFor({state:'hidden'});
  check(await page.evaluate(()=>!window.__mon.plainCalls.some(c=>c.cmd==='save_minutes_markdown')),'playback saved or changed the document');
  return {passed:results.length,results};
}
