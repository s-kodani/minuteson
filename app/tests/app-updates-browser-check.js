async(page)=>{
  const check=(value,message)=>{if(!value)throw Error(message);},results=[];
  const banner=page.getByRole("complementary",{name:"アプリの更新",exact:true});
  await banner.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
  const workspace=page.getByRole("main",{name:"会議ワークスペース",exact:true});
  const sameRect=(before,after,label)=>check(before&&after&&["x","y","width","height"].every(key=>Math.abs(before[key]-after[key])<0.5),label);
  const initialUrl=page.url();
  for(const platform of ["windows","macos"]){
    const url=new URL(initialUrl);url.searchParams.set("resident",platform);
    await page.goto(url.href);
    await banner.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
    const status={channel:platform==="windows"?"windows_store":"macos_release",state:"available",updateAvailable:true,availableVersion:platform==="macos"?"1.0.7":null,errorMessage:null};
    await page.evaluate(status=>window.appUpdateFixture.publish(status),status);
    for(const size of [{width:1200,height:900},{width:960,height:640}]){
      await page.setViewportSize(size);
      await banner.waitFor();
      const shown=await workspace.boundingBox(),heading=await page.locator(".page-heading").boundingBox();
      await page.evaluate(()=>window.appUpdateFixture.publish({state:"no_update",updateAvailable:false}));
      await banner.waitFor({state:"hidden"});
      sameRect(shown,await workspace.boundingBox(),`${platform}: banner reserves workspace area`);
      sameRect(heading,await page.locator(".page-heading").boundingBox(),`${platform}: banner shifts page content`);
      await page.evaluate(status=>window.appUpdateFixture.publish(status),status);
      await banner.waitFor();
      sameRect(shown,await workspace.boundingBox(),`${platform}: showing banner resizes workspace`);
      const surface=await page.locator(".workspace-surface").boundingBox(),box=await banner.boundingBox();
      check(box.x>=surface.x&&box.y>=surface.y&&box.x+box.width<=surface.x+surface.width&&box.y+box.height<=surface.y+surface.height,`${platform}: floating banner escapes workspace`);
      check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`${platform}: floating banner causes horizontal overflow`);
      if(size.width===1200)await page.screenshot({path:`output/playwright/app-update-floating-${platform}.png`});
    }
    if(platform==="macos"){
      const before=await workspace.boundingBox();
      await page.evaluate(()=>window.appUpdateFixture.publish({state:"downloading",downloadedBytes:1048576,totalBytes:2097152}));
      await banner.getByText("1.0 MB / 2.0 MB",{exact:true}).waitFor();
      sameRect(before,await workspace.boundingBox(),"download progress resizes workspace");
      await page.evaluate(()=>window.appUpdateFixture.publish({state:"failed",errorMessage:"取得に失敗しました。接続を確認して再試行してください。".repeat(30)}));
      await banner.getByRole("button",{name:"再試行",exact:true}).waitFor();
      const close=banner.getByRole("button",{name:"あとで",exact:true});
      check(await close.evaluate(button=>{const box=button.getBoundingClientRect();return button.contains(document.elementFromPoint(box.x+box.width/2,box.y+box.height/2));}),"long update failure hides the dismiss control");
    }
  }
  results.push("Windows and macOS floating banners preserve content position and height at 1200×900 and 960×640, with bounded progress and failure states");
  await page.setViewportSize({width:1200,height:900});
  await page.goto(initialUrl);
  await banner.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
  const nav=page.getByRole("navigation",{name:"メインナビゲーション",exact:true});
  const search=page.locator(".meeting-search");
  await search.fill("会議");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"checking"}));
  check(await search.inputValue()==="会議"&&await search.evaluate(element=>element===document.activeElement),"update took editing focus or discarded text");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"available"}));
  await page.locator('.meeting-name').first().click();
  await page.locator('.meeting-detail-navigation').waitFor();
  check(await banner.evaluate(element => element.parentElement.classList.contains('workspace-surface')), 'update banner separates the detail header and tabs');
  const tabs = await page.locator('.meeting-detail-navigation').boundingBox(), box = await banner.boundingBox();
  check(box.y >= tabs.y + tabs.height - 1, 'banner interrupts detail navigation');
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await page.screenshot({path:`output/playwright/app-update-detail-${theme}.png`});
  }
  await page.evaluate(() => document.documentElement.dataset.theme = 'light');
  const detail=await workspace.boundingBox(),detailTabs=await page.locator('.meeting-detail-navigation').boundingBox();
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"no_update",updateAvailable:false}));
  await banner.waitFor({state:"hidden"});
  sameRect(detail,await workspace.boundingBox(),"banner changes detail editor area");
  sameRect(detailTabs,await page.locator('.meeting-detail-navigation').boundingBox(),"banner moves detail tabs");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"available",updateAvailable:true}));
  await banner.waitFor();
  results.push('floating banner stays below detail navigation and above playback without resizing the editor in either theme');
  await nav.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await banner.waitFor();
  await nav.getByRole("button",{name:"設定",exact:true}).click();
  await banner.waitFor();
  const anchored=await banner.boundingBox();
  await workspace.evaluate(element=>{element.scrollTop=element.scrollHeight;});
  sameRect(anchored,await banner.boundingBox(),"scrolling settings moves the floating banner");
  await workspace.evaluate(element=>{element.scrollTop=0;});
  await page.screenshot({path:"output/playwright/app-update-banner.png"});
  results.push("update banner is independent of recording and survives meeting, jobs and settings navigation without taking focus");
  const beforeDismiss=await workspace.boundingBox();
  await banner.getByRole("button",{name:"更新案内を閉じる",exact:true}).click();
  await banner.waitFor({state:"hidden"});
  sameRect(beforeDismiss,await workspace.boundingBox(),"dismissing banner resizes workspace");
  const aboutButton=page.getByRole("button",{name:"このアプリについて",exact:true});
  await page.evaluate(()=>{window.appUpdateFixture.holdRead=true;});
  await aboutButton.scrollIntoViewIfNeeded();await aboutButton.click();
  await page.waitForFunction(()=>window.appUpdateFixture.pendingReads.length>0);
  const about=page.getByRole("dialog",{name:"このアプリについて",exact:true});
  await about.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
  const storeButton=()=>about.getByRole("button",{name:"Microsoft Storeを開く",exact:true});
  const storeChoice=page.getByRole("dialog",{name:"Microsoft Storeで更新します",exact:true});
  const count=name=>page.evaluate(name=>window.appUpdateFixture.calls.filter(x=>x===name).length,name);
  await storeButton().click();
  await storeChoice.getByText("更新前にアプリを終了しますか？",{exact:true}).waitFor();
  await storeChoice.getByText("アプリを一度終了するまで、Microsoft Storeでの更新のインストールは完了しません。",{exact:true}).waitFor();
  check(await storeChoice.getByText(/^対象:/).count()===0,"Store choice repeated an obvious target");
  const gaps=await storeChoice.evaluate(d=>{const r=s=>d.querySelector(s).getBoundingClientRect();return [r(".confirmation-lead").top-r(".action-confirmation h2").bottom,r(".confirmation-actions").top-r(".confirmation-impact").bottom];});
  check(gaps[0]>0&&Math.abs(gaps[0]-gaps[1])<1,`Store choice action spacing ${gaps[1]}px differs from title spacing ${gaps[0]}px`);
  check(await count("open_app_update_page")===0,"Store opened before the exit choice");
  await storeChoice.getByRole("button",{name:"確認をキャンセル",exact:true}).click();
  await storeButton().waitFor();
  check(await count("open_app_update_page")===0&&await count("apply_app_update")===0,"cancelled Store choice opened Store or requested exit");
  await storeButton().click();
  await storeChoice.getByRole("button",{name:"Storeを開くだけ",exact:true}).click();
  await storeButton().waitFor();
  check(await count("open_app_update_page")===1&&await count("apply_app_update")===0,"open-only Store choice requested exit");
  await storeButton().click();
  await storeChoice.getByRole("button",{name:"Storeを開いてアプリを終了",exact:true}).click();
  await page.waitForFunction(()=>window.appUpdateFixture.calls.filter(x=>x==="apply_app_update").length===1);
  check(await count("open_app_update_page")===2,"Store exit choice did not open Store first");
  await page.evaluate(()=>{window.appUpdateFixture.failOpen=true;});
  await storeButton().click();
  await storeChoice.getByRole("button",{name:"Storeを開いてアプリを終了",exact:true}).click();
  await storeChoice.getByText(/配布元を開けませんでした。もう一度お試しください。/).waitFor();
  const failureText=await storeChoice.getByRole("alert").textContent();
  check(failureText==="処理を完了できませんでした。配布元を開けませんでした。もう一度お試しください。 元の画面で状態を再確認してください。自動再実行はしません。",`Store launch failure shows unexpected text: ${failureText}`);
  check(await count("apply_app_update")===1,"failed Store launch still requested exit");
  await storeChoice.getByRole("button",{name:"確認を閉じる",exact:true}).click();
  await page.evaluate(()=>{const f=window.appUpdateFixture;f.failOpen=false;f.failApply=true;});
  await storeButton().click();
  await storeChoice.getByRole("button",{name:"Storeを開いてアプリを終了",exact:true}).click();
  await about.getByText("アプリの終了を開始できませんでした。常駐アイコンの「終了」から終了してください。",{exact:true}).waitFor();
  await page.evaluate(()=>{const f=window.appUpdateFixture;f.failApply=false;f.calls.splice(0);});
  results.push("Store update asks whether to exit, notes deferred installation, and requests the normal exit only after opening Store");
  await page.evaluate(()=>window.appUpdateFixture.publish({channel:"macos_release",availableVersion:"1.0.2"}));
  await page.evaluate(()=>{const f=window.appUpdateFixture;f.holdRead=false;f.pendingReads.splice(0).forEach(resolve=>resolve());});
  await about.getByText("バージョン1.0.2を利用できます",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"downloading",downloadedBytes:1048576,totalBytes:2097152}));
  await about.getByText("更新をダウンロードしています",{exact:true}).waitFor();
  check(await about.getByRole("button",{name:"再起動して更新",exact:true}).isDisabled(),"download offered install before signature verification");
  await about.getByText("1.0 MB / 2.0 MB",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"failed",errorMessage:"合成取得失敗"}));
  await about.getByRole("button",{name:"再試行",exact:true}).click();
  await about.getByText("更新を確認しています",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"ready",errorMessage:null}));
  await about.getByText("更新の準備ができました",{exact:true}).waitFor();
  await page.evaluate(()=>{window.appUpdateFixture.failApply=true;});
  await about.getByRole("button",{name:"再起動して更新",exact:true}).click();
  await about.getByText(/録音・解析・保存などの処理が完了してから更新してください/).waitFor();
  await page.evaluate(()=>{window.appUpdateFixture.failApply=false;});
  await about.getByRole("button",{name:"再起動して更新",exact:true}).click();
  check(await page.evaluate(()=>window.appUpdateFixture.calls.filter(x=>x==="apply_app_update").length===2),"Mac install action not dispatched");
  await page.setViewportSize({width:960,height:740});
  await page.screenshot({path:"output/playwright/app-update-about-macos.png"});
  await page.keyboard.press("Escape");await about.waitFor({state:"hidden"});
  check(await aboutButton.evaluate(element=>element===document.activeElement),"About did not restore focus");
  check(!await banner.isVisible(),"update state changes resurrected dismissed banner");
  await nav.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await nav.getByRole("button",{name:"設定",exact:true}).click();
  check(!await banner.isVisible(),"navigation resurrected dismissed banner");
  await aboutButton.scrollIntoViewIfNeeded();await aboutButton.click();
  await about.getByText("更新の準備ができました",{exact:true}).waitFor();
  results.push("source-specific actions, launch failure, modal focus and dismissed-banner lifetime preserve update information in About");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"unavailable",errorMessage:"合成通信失敗"}));
  await about.getByText("更新を確認できませんでした",{exact:true}).waitFor();
  await about.getByText("合成通信失敗",{exact:true}).waitFor();
  await about.getByRole("button",{name:"もう一度確認",exact:true}).click();
  await about.getByText("更新を確認しています",{exact:true}).waitFor();
  check(await about.getByRole("button",{name:"確認中…",exact:true}).isDisabled(),"pending check not disabled");
  await page.keyboard.press("Escape");await about.waitFor({state:"hidden"});
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"no_update",updateAvailable:false,availableVersion:null,errorMessage:null}));
  await aboutButton.click();await about.getByText("公開されている新版は見つかりませんでした",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({channel:"unsupported",state:"unsupported"}));
  await about.getByText("この配布版は更新確認の対象外です",{exact:true}).waitFor();
  check(await about.getByRole("button",{name:"更新を確認",exact:true}).count()===0,"unsupported build offered a check");
  const calls=await page.evaluate(()=>window.monBrowserFixture.calls.map(x=>x.command));
  check(!calls.some(x=>["finish_main_close","stop_recording","start_recording"].includes(x)),"availability UI started or stopped application work");
  results.push("offline, pending, recovered no-update and unsupported states never trigger installation, recording stop or application exit");
  return results;
}
