async(page)=>{
  const check=(value,message)=>{if(!value)throw Error(message);},results=[];
  const banner=page.getByRole("complementary",{name:"アプリの更新",exact:true});
  await banner.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
  const nav=page.getByRole("navigation",{name:"メインナビゲーション",exact:true});
  const search=page.locator(".meeting-search");
  await search.fill("会議");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"checking"}));
  check(await search.inputValue()==="会議"&&await search.evaluate(element=>element===document.activeElement),"update took editing focus or discarded text");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"available"}));
  await nav.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await banner.waitFor();
  await nav.getByRole("button",{name:"設定",exact:true}).click();
  await banner.waitFor();
  await page.screenshot({path:"output/playwright/app-update-banner.png"});
  results.push("update banner is independent of recording and survives meeting, jobs and settings navigation without taking focus");
  const aboutButton=page.getByRole("button",{name:"このアプリについて",exact:true});
  await page.evaluate(()=>{window.appUpdateFixture.holdRead=true;});
  await aboutButton.scrollIntoViewIfNeeded();await aboutButton.click();
  await page.waitForFunction(()=>window.appUpdateFixture.pendingReads.length>0);
  const about=page.getByRole("dialog",{name:"このアプリについて",exact:true});
  await about.getByText("Microsoft Storeに更新があります",{exact:true}).waitFor();
  await about.getByRole("button",{name:"Microsoft Storeを開く",exact:true}).click();
  check(await page.evaluate(()=>window.appUpdateFixture.calls.filter(x=>x==="open_app_update_page").length===1),"Store action was not dispatched exactly once");
  await page.evaluate(()=>{window.appUpdateFixture.failOpen=true;});
  await about.getByRole("button",{name:"Microsoft Storeを開く",exact:true}).click();
  await about.getByText("配布元を開けませんでした。もう一度お試しください。",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({channel:"macos_release",availableVersion:"1.0.2"}));
  await page.evaluate(()=>{const f=window.appUpdateFixture;f.holdRead=false;f.pendingReads.splice(0).forEach(resolve=>resolve());});
  await about.getByText("バージョン1.0.2を利用できます",{exact:true}).waitFor();
  await about.getByRole("button",{name:"ダウンロードページを開く",exact:true}).waitFor();
  await page.setViewportSize({width:960,height:740});
  await page.screenshot({path:"output/playwright/app-update-about-macos.png"});
  await page.keyboard.press("Escape");await about.waitFor({state:"hidden"});
  check(await aboutButton.evaluate(element=>element===document.activeElement),"About did not restore focus");
  await banner.getByRole("button",{name:"更新案内を閉じる",exact:true}).click();
  await banner.waitFor({state:"hidden"});
  await nav.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await nav.getByRole("button",{name:"設定",exact:true}).click();
  check(!await banner.isVisible(),"navigation resurrected dismissed banner");
  await aboutButton.scrollIntoViewIfNeeded();await aboutButton.click();
  await about.getByText("バージョン1.0.2を利用できます",{exact:true}).waitFor();
  results.push("source-specific actions, launch failure, modal focus and dismissed-banner lifetime preserve update information in About");
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"unavailable",errorMessage:"合成通信失敗"}));
  await about.getByText("更新を確認できませんでした",{exact:true}).waitFor();
  await about.getByText("合成通信失敗",{exact:true}).waitFor();
  await about.getByRole("button",{name:"もう一度確認",exact:true}).click();
  await about.getByText("更新を確認しています",{exact:true}).waitFor();
  check(await about.getByRole("button",{name:"確認中…",exact:true}).isDisabled(),"pending check not disabled");
  await page.keyboard.press("Escape");await about.waitFor({state:"hidden"});
  await page.evaluate(()=>window.appUpdateFixture.publish({state:"no_update",updateAvailable:false,availableVersion:null,errorMessage:null}));
  await aboutButton.click();await about.getByText("公開されている新版は見つかりませんでした",{exact:true}).waitFor();
  await page.evaluate(()=>window.appUpdateFixture.publish({channel:"unsupported",state:"unsupported"}));
  await about.getByText("この配布版は更新確認の対象外です",{exact:true}).waitFor();
  check(await about.getByRole("button",{name:"更新を確認",exact:true}).count()===0,"unsupported build offered a check");
  const calls=await page.evaluate(()=>window.monBrowserFixture.calls.map(x=>x.command));
  check(!calls.some(x=>["finish_main_close","stop_recording","start_recording"].includes(x)),"availability UI started or stopped application work");
  results.push("offline, pending, recovered no-update and unsupported states never trigger installation, recording stop or application exit");
  return results;
}
