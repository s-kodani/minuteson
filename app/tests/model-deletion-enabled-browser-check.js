  const boot=async()=>{await page.goto(`${baseUrl}/tests/model-deletion-enabled-browser.html?resident=windows`);await button().waitFor();await page.waitForFunction(()=>!document.querySelector(".deletion-trigger")?.disabled);};
  await boot();
