async (page, capturePath) => {
  const results = [];
  const check = (condition, message) => { if (!condition) throw Error(message); };
  const history = () => page.getByRole("dialog", { name: "データ復元結果", exact: true });
  const review = () => page.getByRole("dialog", { name: "元データの削除を確認", exact: true });
  const launch = () => page.getByRole("button", { name: "復元結果と元データの保存先を確認", exact: true });
  const confirm = () => review().getByRole("button", { name: "元データを削除する", exact: true });
  const initial = () => history().getByRole("button", { name: "元データを削除…", exact: true });
  const retry = () => history().getByRole("button", { name: "元データの削除を続ける…", exact: true });
  const completed = () => history().getByRole("status").filter({ hasText: "確認した元データの削除が完了しました。" });
  const count = () => page.evaluate(() => window.salvageCleanupFixture.calls.length);
  const open = async () => { await launch().click(); await history().getByText("/safe/元の会議データ", { exact: true }).waitFor(); };
  const close = async () => { await history().getByRole("button", { name: "復元結果を閉じる", exact: true }).click(); await history().waitFor({ state: "hidden" }); };
  const patch = values => page.evaluate(values => Object.assign(window.salvageCleanupFixture, values), values);
  const shot = name => page.screenshot({ path: capturePath(`${name}.png`), animations: "disabled" });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "設定", exact: true }).click();
  await launch().waitFor();
  await launch().scrollIntoViewIfNeeded();
  await shot("source-cleanup-history-entry");
  await page.setViewportSize({ width: 1360, height: 900 });
  await open();
  await initial().waitFor();
  await history().getByRole("row").filter({ hasText: "運用手順の見直し" }).getByText("削除済み", { exact: true }).waitFor();
  check(await count() === 0, "opening rescue history deleted original data");
  await shot("source-cleanup-history");
  await initial().click();
  await review().locator(".salvage-source-confirmation").getByText("/safe/元の会議データ", { exact: true }).waitFor();
  await review().getByText("3 件", { exact: true }).waitFor();
  await review().getByText("12 件", { exact: true }).waitFor();
  await review().getByText("復元済みの音声ファイル", { exact: true }).waitFor();
  await review().getByText(/復元できなかったデータも含まれる場合/).waitFor();
  await page.waitForFunction(() => document.activeElement?.getAttribute("aria-label") === "削除をキャンセル");
  await page.setViewportSize({ width: 400, height: 720 });
  check(await review().evaluate(element => element.scrollWidth <= element.clientWidth + 1), "confirmation overflowed in a narrow window");
  await page.setViewportSize({ width: 1360, height: 900 });
  check(await count() === 0, "preview dispatched deletion");
  await shot("source-cleanup-confirmation");
  await page.keyboard.press("Escape");
  await history().waitFor();
  check(await initial().evaluate(button => document.activeElement === button), "cancellation did not return focus to the review opener");
  check(await count() === 0, "Escape dispatched deletion");
  results.push("opening and cancelling an explicit confirmation preserves the original and restores focus");

  await initial().click();
  await page.evaluate(() => { window.salvageCleanupFixture.status.audioFiles = 9; });
  await confirm().click();
  await history().getByRole("alert").filter({ hasText: "削除対象の状態が変わりました" }).waitFor();
  check(await count() === 0, "changed preview submitted the original confirmation");
  await initial().click();
  await review().getByText("9 件", { exact: true }).waitFor();
  await patch({ mode: "hold" });
  await confirm().click();
  await review().getByText("元データを削除しています。", { exact: true }).waitFor();
  check(await confirm().isDisabled() && await review().getByRole("button", { name: "キャンセル", exact: true }).isDisabled(), "deletion allowed a duplicate dispatch or dismissal");
  await page.keyboard.press("Escape");
  check(await review().isVisible() && await count() === 1, "Escape closed or replayed deletion while running");
  await shot("source-cleanup-running");
  await page.evaluate(() => window.salvageCleanupFixture.finish());
  await completed().waitFor();
  check(await initial().count() === 0 && await count() === 1, "confirmed cleanup offered a second deletion");
  await shot("source-cleanup-completed");
  await close();
  await open();
  await completed().waitFor();
  results.push("changed scope requires fresh confirmation and successful result is retained on reopen");

  await close();
  const available = { sourceRoot: "/safe/元の会議データ", databaseFiles: 3, audioFiles: 12, state: "available" };
  await patch({ mode: "interrupt", status: available });
  await open();
  await initial().click();
  await confirm().click();
  await history().getByRole("status").filter({ hasText: "元データの削除が中断しました。" }).waitFor();
  await history().getByRole("alert").filter({ hasText: "削除を完了できませんでした" }).waitFor();
  check(await count() === 2, "interrupted deletion was automatically retried");
  await shot("source-cleanup-interrupted");
  await retry().click();
  await patch({ mode: "lostAfterSuccess" });
  await confirm().click();
  await completed().waitFor();
  check(await count() === 3 && await history().getByRole("alert").count() === 0, "lost response did not reconcile to the recorded result");
  results.push("interrupted work requires a new confirmation, and lost success reconciles without replay");

  await close();
  await patch({ mode: "unknown", status: available });
  await open();
  await initial().click();
  await confirm().click();
  const recheck = history().getByRole("button", { name: "削除状態を再確認", exact: true });
  await recheck.waitFor();
  check(await initial().count() === 0 && await count() === 4, "unknown response offered immediate redispatch");
  await shot("source-cleanup-unknown");
  await recheck.click();
  await initial().waitFor();
  check(await count() === 4, "checking an unknown result replayed deletion");
  await close();

  await patch({ status: null });
  await open();
  await history().getByText("元の保存先で削除できるファイルを確認できませんでした。", { exact: true }).waitFor();
  check(await initial().count() === 0 && await count() === 4, "missing authorization offered deletion");
  await shot("source-cleanup-unavailable");
  await close();
  await patch({ status: { ...available, sourceRoot: "/safe/異なる保存先" } });
  await open();
  await history().getByRole("alert").filter({ hasText: "復元元のファイルを確認できませんでした" }).waitFor();
  check(await initial().count() === 0 && await count() === 4, "unmatched old data was eligible for deletion");
  results.push("unknown, absent and mismatched evidence preserve the rescue history without dispatching deletion");

  await close();
  await patch({ status: available });
  await page.evaluate(() => { window.dataFixture.blocker = "録音・音声保存中"; });
  await open();
  await history().getByText(/現在は元データを削除できません/).waitFor();
  check(await initial().isDisabled() && await count() === 4, "global maintenance conflict made history inaccessible or admitted deletion");
  await shot("source-cleanup-busy");
  results.push("global maintenance conflict disables only source deletion and leaves the rescue report available");

  await close();
  await page.evaluate(() => { window.dataFixture.blocker = null; });
  await page.getByRole("button", { name: "バックアップを作成", exact: true }).waitFor();
  await page.waitForFunction(() => [...document.querySelectorAll("main button")].some(button => button.textContent === "バックアップを作成" && !button.disabled));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await patch({ resultMode: "hold" });
  await launch().click();
  await history().getByRole("status").filter({ hasText: "読み込み中です。" }).waitFor();
  await shot("source-cleanup-history-loading");
  await page.evaluate(() => window.salvageCleanupFixture.finishResult());
  await history().getByText("/safe/元の会議データ", { exact: true }).waitFor();
  await close();
  await patch({ resultMode: "empty" });
  await launch().click();
  await history().getByText("この保存先の復元記録はありません。", { exact: true }).waitFor();
  await shot("source-cleanup-history-empty");
  await close();
  await patch({ resultMode: "error" });
  await launch().click();
  await history().getByRole("alert").filter({ hasText: "復元結果を読み込めませんでした。" }).waitFor();
  await shot("source-cleanup-history-error");
  results.push("history distinguishes loading, empty and failed reads without claiming deletion targets");
  await page.reload();
  await page.getByRole("button", { name: "設定", exact: true }).click();
  await patch({ status: { ...available, state: "completed", retainedAudioFiles: 2 } });
  await open();
  await completed().filter({ hasText: "元のファイルと確認できなかった音声 2 件は削除しませんでした。" }).waitFor();
  await shot("source-cleanup-completed-retained-audio");
  check(await initial().count() === 0, "retained source audio was offered for deletion again");
  results.push("completed cleanup reports unverified audio separately from deleted files");
  return results;
}
