async (page, capturePath) => {
  const results = [], check = (value, message) => { if (!value) throw Error(message); };
  const dialog = page.getByRole('dialog', { name: 'AIモデルの実行環境を更新できます', exact: true });
  await dialog.waitFor();
  await dialog.screenshot({ path: capturePath('model-runtime-guidance-desktop.png') });
  check(await dialog.getByRole('listitem').count() === 1, 'unused installed runtime was omitted');
  check(!await page.evaluate(() => window.modelDownloadFixture.calls.some(c => ['start_model_download','check_model_compatibility','apply_model_profile_application'].includes(c.command))), 'startup guidance executed model work');
  await dialog.getByRole('button', { name: 'モデルの設定を開く', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const update = page.getByRole('button', { name: '実行環境を更新して使用', exact: true });
  await update.waitFor();
  await page.waitForFunction(() => document.activeElement?.textContent === '実行環境を更新して使用');
  results.push('unused installed model is detected without executing it; settings selects and focuses the update action');
  await page.getByRole('button', { name: '案内を再描画', exact: true }).click();
  await page.getByRole('button', { name: '案内を再描画', exact: true }).click();
  check(!await dialog.isVisible(), 'remount repeated startup guidance');
  await page.reload(); await dialog.waitFor();
  await dialog.getByRole('button', { name: 'あとで', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.reload(); await dialog.waitFor();
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'hidden' });
  results.push('opening settings, later and Escape defer only this launch; a new process reevaluates the need');
  await page.goto(new URL('/?other=1', page.url()).href);
  const other = page.getByRole('dialog', { name: '先行する確認', exact: true });
  await other.waitFor(); check(!await dialog.isVisible(), 'startup modal stacked on another modal');
  await other.getByRole('button', { name: '確認を閉じる', exact: true }).click(); await dialog.waitFor();
  await page.setViewportSize({ width: 390, height: 700 });
  check(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth), 'runtime guidance overflows at narrow width');
  await dialog.screenshot({ path: capturePath('model-runtime-guidance.png') });
  results.push('guidance waits for an existing modal and fits narrow windows');
  await page.goto(new URL('/?locked=1', page.url()).href);
  await page.getByRole('button', { name: '設定', exact: true }).waitFor();
  check(!await dialog.isVisible(), 'guidance appeared during a conflicting operation');
  await page.evaluate(() => window.modelDownloadFixture.setRuntimeLocked(false)); await dialog.waitFor();
  await page.goto(new URL('/?empty=1', page.url()).href);
  await page.getByRole('button', { name: '設定', exact: true }).waitFor();
  check(!await dialog.isVisible(), 'guidance appeared without installed updates');
  results.push('conflicting operations defer guidance and an empty installation has no runtime prompt');
  return results;
}
