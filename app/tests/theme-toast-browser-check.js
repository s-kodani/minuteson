// Current settings and real Sonner host, with synthetic durable preferences.
async (page,capturePath)=>{
  const results=[],check=(ok,message)=>{if(!ok)throw Error(message);};
  const host=page.locator('.toast-host'),settings=()=>page.getByRole('region',{name:'表示設定',exact:true});
  const select=()=>settings().getByRole('combobox',{name:'表示モード',exact:true});
  const nav=()=>page.locator('.sidebar');
  const count=()=>page.evaluate(()=>window.themeFixture.calls.filter(c=>c.command==='save_ui_preferences').length);
  const open=async()=>{await nav().getByRole('button',{name:'設定',exact:true}).click();await select().waitFor();};
  const waitTheme=t=>page.waitForFunction(t=>document.documentElement.dataset.theme===t,t);
  await page.evaluate(()=>window.themeFixture.reset());await page.reload();await open();
  await page.clock.runFor(2700);
  check(await host.locator('.toast-card').filter({hasText:/表示設定/}).count()===0,'periodic theme reads notified');
  await select().selectOption('dark');await host.getByRole('status').filter({hasText:'表示設定を保存しました'}).waitFor();
  const first=await host.locator('.toast-success').getAttribute('data-toast-id');
  await host.getByRole('button',{name:'成功通知を閉じる',exact:true}).click();
  await host.locator('.toast-success').waitFor({state:'hidden'});
  await nav().getByRole('button',{name:'会議一覧',exact:true}).click();await open();
  check(await host.locator('.toast-card').filter({hasText:/表示設定/}).count()===0,'navigation replayed dismissed theme save');
  await select().selectOption('light');await host.getByRole('status').filter({hasText:'表示設定を保存しました'}).waitFor();
  check(await host.locator('.toast-success').getAttribute('data-toast-id')!==first,'next explicit save lost its identity');
  await host.getByRole('button',{name:'成功通知を閉じる',exact:true}).click();
  await host.locator('.toast-success').waitFor({state:'hidden'});
  results.push('reads and navigation stay silent; explicit saves have distinct dismissible notification identities');
  await page.evaluate(()=>window.themeFixture.mode='fail');await select().selectOption('dark');
  await host.getByRole('alert').filter({hasText:'表示設定の読込・保存'}).waitFor();
  await host.locator('.toast-error').hover();
  const failed=await count();await host.getByRole('button',{name:'エラー通知を閉じる',exact:true}).click();
  check(await settings().getByRole('button',{name:'テーマの保存を再試行',exact:true}).isVisible()&&await select().inputValue()==='dark','dismissal lost retained choice or safe retry');
  await page.clock.runFor(2700);check(await count()===failed&&await host.locator('.toast-error').count()===0,'poll replayed failure or write');
  await page.evaluate(()=>window.themeFixture.mode='success');await settings().getByRole('button',{name:'テーマの保存を再試行',exact:true}).click();await waitTheme('dark');
  check(await count()===failed+1,'explicit retry duplicated write');
  results.push('dismissed failure preserves issue and choice; polling stays silent; explicit save retry resolves');
  await page.evaluate(()=>window.themeFixture.mode='fail');await select().selectOption('light');
  await host.getByRole('button',{name:'テーマの保存を再試行',exact:true}).waitFor();
  await page.evaluate(()=>window.themeFixture.mode='success');await host.getByRole('button',{name:'テーマの保存を再試行',exact:true}).click();await waitTheme('light');
  results.push('toast retry uses the retained selection through the guarded controller');
  await page.evaluate(()=>window.themeFixture.mode='lostUnreadable');await select().selectOption('dark');
  await host.getByRole('alert').filter({hasText:'保存結果を確認できません'}).waitFor();
  const unknown=await count();check(await select().isDisabled(),'unknown commit permits another write');
  await page.evaluate(()=>window.themeFixture.readFail=false);await waitTheme('dark');check(await count()===unknown,'readback repeated unknown save');
  await page.screenshot({path:capturePath('theme-toast-dark.png')});
  results.push('unknown acknowledgement locks writes and recovers by readback without another save');
  return {passed:results.length,results};
}
