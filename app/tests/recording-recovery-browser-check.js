async (page, capturePath) => {
  const results=[];
  const check=(v,message)=>{if(!v)throw Error(message);};
  const url="http://127.0.0.1:1420/tests/recording-recovery-browser.html?resident=windows";
  await page.goto(url);
  const common=()=>page.getByRole("region",{name:"進行中の処理",exact:true});
  await common().getByText("録音を保存中",{exact:true}).waitFor();
  await page.getByRole("cell",{name:"録音の保存待ち",exact:true}).waitFor();
  if(capturePath)await page.screenshot({path:capturePath("recording-recovery-active.png")});
  await common().getByRole("button",{name:/進行中の処理 2 件/}).click();
  await page.getByRole("heading",{name:"ジョブ一覧",exact:true}).waitFor();
  check(await page.getByRole("region",{name:"バックグラウンドのジョブ一覧"}).getByRole("progressbar").count()===2,"recovery jobs missing");
  results.push("common progress, job navigation and two recovery rows");
  await page.reload();
  await common().getByText("録音を保存中",{exact:true}).waitFor();
  results.push("reload restores native inventory");
  await page.getByRole("button",{name:"回復中の会議の操作",exact:true}).click();
  check(await page.getByRole("menuitem",{name:"回復中の会議を削除",exact:true}).isDisabled(),"active recovery deletable");
  await page.getByText("録音を保存中です。完了するまで削除できません。",{exact:true}).waitFor();
  check(await page.getByRole("menuitem",{name:"録音画面で確認",exact:true}).count()===0,"recovery incorrectly routes to live recording");
  await page.getByRole("menuitem",{name:"ジョブ一覧で確認",exact:true}).click();
  await page.getByRole("heading",{name:"ジョブ一覧",exact:true}).waitFor();
  await page.locator(".job-list-rows > li").filter({hasText:"回復中の会議"}).waitFor();
  await page.getByRole("button",{name:"前の画面へ戻る",exact:true}).click();
  await page.getByRole("button",{name:"回復待ちの会議の操作",exact:true}).click();
  check(await page.getByRole("menuitem",{name:"回復待ちの会議を削除",exact:true}).isEnabled(),"queued display blocked native deletion permission");
  check(await page.getByRole("menuitem",{name:"ジョブ一覧で確認",exact:true}).isEnabled(),"queued recovery has no route to Jobs");
  await page.keyboard.press("Escape");
  results.push("native deletion blocks active work only and opens the recovered meeting's save in Jobs");
  await page.evaluate(()=>{window.recordingRecoveryFixture.fail=true;});
  await page.clock.runFor(1200);
  check(await page.locator(".toast-card").filter({hasText:"保存状態を確認できません"}).count()===0,"automatic recovery read notified");
  await page.getByRole("row").filter({hasText:"回復中の会議"}).getByRole("cell",{name:/録音を保存中/}).waitFor();
  await page.getByText("保存状態を確認できません。表示は前回取得した状態です。",{exact:true}).first().waitFor();
  await page.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await page.getByRole("status").filter({hasText:"ジョブの状態を確認中"}).waitFor();
  check(await page.getByRole("heading",{name:"進行中のジョブはありません",exact:true}).count()===0,"failed read showed empty success");
  results.push("failed reads retain progress and suppress empty success");
  await page.evaluate(()=>{window.recordingRecoveryFixture.fail=false;});
  await page.getByRole("status").filter({hasText:"ジョブの状態を確認中"}).waitFor({state:"hidden"});
  await page.evaluate(()=>window.recordingRecoveryFixture.finish());
  await common().waitFor({state:"hidden"});
  await page.getByRole("heading",{name:"進行中のジョブはありません",exact:true}).waitFor();
  await page.waitForFunction(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.level==="success"&&n.eventId?.startsWith("recording_save:")).length===2);
  check(await page.evaluate(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.level==="success"&&n.eventId?.startsWith("recording_save:")).every(n=>n.message==="録音を保存完了しました。")),"save completion notification differs from the required wording");
  check(await page.getByText("録音を回復し、保存を完了しました。",{exact:true}).count()===0,"legacy recovery completion wording remains");
  await page.evaluate(()=>{window.recordingRecoveryFixture.stale=true;});
  await page.clock.runFor(1200);
  check(await common().count()===0,"stale reply revived recovery");
  await page.getByRole("button",{name:"会議一覧",exact:true}).first().click();
  check(await page.getByRole("cell",{name:"録音済み",exact:true}).count()===2,"missed events left stale meeting rows");
  results.push("silent completion is reconciled by polling, including meeting rows; stale replies cannot revive progress");
  await page.evaluate(async()=>{const r=window.recordingRecoveryFixture;r.stale=false;window.dataFixture.meetings[0].lifecycle="recording";await r.change({phase:"completed",items:[{...r.snapshot.items[0],phase:"failed",error:"合成manifest検証失敗"}]});});
  await page.getByText(/音声を保存できませんでした。/).first().waitFor();
  await page.reload();
  await page.getByRole("row").filter({hasText:"回復中の会議"}).getByRole("cell",{name:/音声保存エラー/}).waitFor();
  await page.evaluate(async()=>{
    const r=window.recordingRecoveryFixture,item=r.snapshot.items[0];
    await r.recordChanged({phase:"error",sessionId:item.sessionId,meetingId:item.meetingId,errorMessage:"合成manifest検証失敗"});
    const error="合成manifest検証失敗（最新の詳細）";
    await r.change({phase:"failed",error,items:[{...item,error}]});
  });
  await page.waitForFunction(()=>window.recordingRecoveryFixture.notificationHistory().some(n=>n.eventId==="recording_save:session-0:failed"&&n.message.includes("最新の詳細")));
  check(await page.evaluate(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.eventId==="recording_save:session-0:failed").length)===1,"one failed recording produced duplicate recorder/recovery notifications");
  check(await page.evaluate(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.message.includes("最新の詳細")).length)===1,"global and per-session errors produced duplicate save failure notifications");
  if(capturePath)await page.screenshot({path:capturePath("recording-recovery-failure.png")});
  results.push("failed recovery remains visible without an endless progress bar");
  const row=page.getByRole("row").filter({hasText:"回復中の会議"});
  const trigger=row.getByRole("button",{name:"回復中の会議の操作",exact:true});
  const menu=page.getByRole("menu",{name:"回復中の会議の操作",exact:true});
  const retry=menu.getByRole("menuitem",{name:"保存を再試行",exact:true});
  check(await row.getByRole("button",{name:"保存を再試行",exact:true}).count()===0&&await row.getByRole("menuitem",{name:"保存を再試行",exact:true}).count()===0,"save retry is visible outside the row menu");
  await trigger.click();
  check(await retry.isEnabled(),"failed recording has no enabled save retry in its row menu");
  await page.keyboard.press("ArrowDown");
  check(await retry.evaluate(button=>button===document.activeElement),"keyboard navigation skipped save retry");
  if(capturePath)await page.screenshot({path:capturePath("recording-recovery-retry-menu.png")});
  await page.keyboard.press("Escape");
  check(await trigger.evaluate(button=>button===document.activeElement)&&await menu.count()===0,"Escape did not close the menu and restore its trigger");
  await trigger.click();
  await retry.click();
  check(await menu.count()===0,"save retry did not close the row menu");
  await row.getByRole("cell",{name:"録音を保存中",exact:true}).waitFor();
  check(await page.evaluate(()=>window.recordingRecoveryFixture.calls.filter(command=>command==="retry_recording_recovery").length)===1,"retry submitted more than once");
  await page.evaluate(()=>window.recordingRecoveryFixture.finish());
  await row.getByRole("cell",{name:"録音済み",exact:true}).waitFor();
  await trigger.click();
  check(await retry.count()===0,"saved recording still offers retry");
  await page.keyboard.press("Escape");
  results.push("save retry completes without restart and removes the obsolete failed status");

  await page.evaluate(()=>window.recordingRecoveryFixture.recordChanged({phase:"idle",sessionId:null,meetingId:null,errorMessage:null}));
  await page.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await page.evaluate(async()=>{
    const r=window.recordingRecoveryFixture,item={...r.snapshot.items[0],sessionId:"normal-session",phase:"running",startedAtMs:Date.now(),error:null,progress:{stage:"verifying_audio",completed:1,total:2,unit:"files"}};
    await r.recordChanged({phase:"stopping",sessionId:item.sessionId,meetingId:item.meetingId,errorMessage:null});
    await r.change({runId:"normal-save",phase:"scanning",origin:"stop",targetSessionId:item.sessionId,items:[item]});
  });
  await page.locator('.job-list-rows>li').getByText("保存対象を確認中",{exact:true}).waitFor();
  check(await page.locator('.job-list-rows>li').count()===1,"target scan duplicated the normal stopping job");
  await page.evaluate(()=>window.recordingRecoveryFixture.change({phase:"running"}));
  await page.locator('.job-list-rows>li').getByText("生成音声を検証中",{exact:true}).waitFor();
  check(await page.locator('.job-list-rows>li').count()===1,"normal stop and inner save produced two job rows");
  check(await page.locator('.job-nav-count').innerText()==="1","one save session was counted twice in navigation");
  check(await common().getByRole("progressbar").count()===1&&await common().locator('.progress-jobs-link').count()===0,"one save session was counted twice in common progress");
  check(await page.locator('.job-list-rows>li .job-kind').innerText()==="録音の保存","normal save retained a separate recovery kind");
  await page.locator(".sidebar").getByRole("button",{name:"会議一覧",exact:true}).click();
  await page.getByRole("button",{name:"回復中の会議の操作",exact:true}).click();
  await page.getByRole("menuitem",{name:"録音画面で確認",exact:true}).waitFor();
  check(await page.getByRole("menuitem",{name:"ジョブ一覧で確認",exact:true}).count()===0,"the matching live recording save used the historical recovery route");
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  results.push("normal stopping and inner saving share one row, count and latest saving stage");
  await page.evaluate(()=>window.recordingRecoveryFixture.finish());
  await page.getByRole("heading",{name:"進行中のジョブはありません",exact:true}).waitFor();
  await page.evaluate(()=>window.recordingRecoveryFixture.recordChanged({phase:"saving"}));
  await page.clock.runFor(1200);
  check(await common().count()===0&&await page.locator('.job-list-rows>li').count()===0&&await page.locator('.job-nav-count').count()===0,"delayed recorder saving revived a completed save job");
  check(await page.evaluate(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.eventId==="recording_save:normal-session:succeeded").length)===1,"normal save completion notification was duplicated");
  results.push("terminal save evidence suppresses late recorder progress without repeating the completion notification");

  const warning="破損箇所の直前までの音声を保存しました。元音声は保持しています。";
  await page.evaluate(async warning=>{
    const r=window.recordingRecoveryFixture,item={...r.snapshot.items[0],sessionId:"partial-session",phase:"succeeded",error:null,warning};
    await r.recordChanged({phase:"saving",sessionId:item.sessionId,meetingId:item.meetingId,errorMessage:null});
    await r.change({runId:"partial-save",phase:"completed",origin:"stop",targetSessionId:item.sessionId,error:null,items:[item]});
  },warning);
  const partial=page.locator(".toast-card").filter({hasText:warning});
  await partial.waitFor();
  check(await partial.getByRole("button",{name:"保存を再試行",exact:true}).count()===0,"partial success offered a save retry");
  await page.evaluate(async()=>{
    const r=window.recordingRecoveryFixture;
    await r.recordChanged({phase:"error",errorMessage:"遅延した外側の保存失敗"});
    await r.change({items:r.snapshot.items.map(item=>({...item}))});
  });
  await page.clock.runFor(1200);
  const partialHistory=await page.evaluate(()=>window.recordingRecoveryFixture.notificationHistory().filter(n=>n.eventId?.startsWith("recording_save:partial-session:")));
  check(partialHistory.length===1&&partialHistory[0].level==="warning"&&partialHistory[0].message.includes(warning),"partial-save warning was duplicated or replaced by a stale recorder result");
  check(await common().count()===0&&await page.locator('.job-list-rows>li').count()===0,"partial success revived a saving job");
  await page.getByRole("button",{name:"会議一覧",exact:true}).first().click();
  const partialRow=page.getByRole("row").filter({hasText:"回復中の会議"});
  await partialRow.getByRole("cell",{name:"録音済み",exact:true}).waitFor();
  check(await partialRow.getByRole("button",{name:"保存を再試行",exact:true}).count()===0,"partial success remained a save error in the meeting list");
  results.push("partial save publishes one warning, retains the recorded meeting and suppresses late errors without a retry action");
  return {passed:results.length,results};
}
