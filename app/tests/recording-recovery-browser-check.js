async (page, capturePath, platform = "windows") => {
  const results=[];
  const check=(v,message)=>{if(!v)throw Error(message);};
  const url=`http://127.0.0.1:1420/tests/recording-recovery-browser.html?resident=${platform}`;
  await page.goto(url);
  const common=()=>page.getByRole("region",{name:"進行中の処理",exact:true});
  await common().getByText("録音を回復中",{exact:true}).waitFor();
  await page.getByRole("cell",{name:"録音の回復待ち",exact:true}).waitFor();
  if(capturePath)await page.screenshot({path:capturePath("recording-recovery-active.png")});
  await common().getByRole("button",{name:/進行中の処理 2 件/}).click();
  await page.getByRole("heading",{name:"ジョブ一覧",exact:true}).waitFor();
  check(await page.getByRole("region",{name:"バックグラウンドのジョブ一覧"}).getByRole("progressbar").count()===2,"recovery jobs missing");
  results.push("common progress, job navigation and two recovery rows");
  await page.reload();
  await common().getByText("録音を回復中",{exact:true}).waitFor();
  results.push("reload restores native inventory");
  await page.getByRole("button",{name:"回復中の会議の操作",exact:true}).click();
  check(await page.getByRole("menuitem",{name:"回復中の会議を削除",exact:true}).isDisabled(),"active recovery deletable");
  await page.getByText("録音を回復中です。完了するまで削除できません。",{exact:true}).waitFor();
  await page.keyboard.press("Escape");
  await page.getByRole("button",{name:"回復待ちの会議の操作",exact:true}).click();
  check(await page.getByRole("menuitem",{name:"回復待ちの会議を削除",exact:true}).isEnabled(),"queued display blocked native deletion permission");
  await page.keyboard.press("Escape");
  results.push("native deletion blocks active work only");
  await page.evaluate(()=>{window.recordingRecoveryFixture.fail=true;});
  await page.getByText(/回復状態を確認できません。表示は前回取得した状態です。/).first().waitFor();
  await common().getByText("録音を回復中",{exact:true}).waitFor();
  await page.getByRole("button",{name:"ジョブ一覧",exact:true}).click();
  await page.getByText("ジョブの状態を取得できません。表示は前回取得した状態です。自動で再確認します。",{exact:true}).waitFor();
  check(await page.getByRole("heading",{name:"進行中のジョブはありません",exact:true}).count()===0,"failed read showed empty success");
  results.push("failed reads retain progress and suppress empty success");
  await page.evaluate(()=>{window.recordingRecoveryFixture.fail=false;});
  await page.waitForFunction(()=>!document.querySelector('.job-read-error'));
  await page.evaluate(()=>window.recordingRecoveryFixture.finish());
  await common().waitFor({state:"hidden"});
  await page.getByRole("heading",{name:"進行中のジョブはありません",exact:true}).waitFor();
  await page.evaluate(()=>{window.recordingRecoveryFixture.stale=true;});
  await page.waitForTimeout(1200);
  check(await common().count()===0,"stale reply revived recovery");
  await page.getByRole("button",{name:"会議一覧",exact:true}).first().click();
  check(await page.getByRole("cell",{name:"録音済み",exact:true}).count()===2,"missed events left stale meeting rows");
  results.push("silent completion is reconciled by polling, including meeting rows; stale replies cannot revive progress");
  await page.evaluate(async()=>{const r=window.recordingRecoveryFixture;r.stale=false;window.dataFixture.meetings[0].lifecycle="recording";await r.change({phase:"completed",items:[{...r.snapshot.items[0],phase:"failed",error:"合成manifest検証失敗"}]});});
  await page.getByText(/回復できませんでした。録音は未完了のまま保持しています。/).first().waitFor();
  await page.reload();
  await page.getByRole("cell",{name:/録音未完了・要確認/}).waitFor();
  if(capturePath)await page.screenshot({path:capturePath("recording-recovery-failure.png")});
  results.push("failed recovery remains visible without an endless progress bar");
  return {passed:results.length,results};
}
